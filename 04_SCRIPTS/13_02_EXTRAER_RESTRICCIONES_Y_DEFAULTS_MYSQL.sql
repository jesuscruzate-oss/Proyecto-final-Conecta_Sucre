-- Exportar el resultado como 13_02_CONSTRAINTS_MYSQL.csv
-- Recupera PK, UK, FK, CHECK y columnas que participan en cada restriccion.
SELECT tc.TABLE_NAME AS tabla, tc.CONSTRAINT_NAME AS restriccion,
       tc.CONSTRAINT_TYPE AS tipo_restriccion,
       kcu.COLUMN_NAME AS columna, kcu.ORDINAL_POSITION AS posicion,
       kcu.REFERENCED_TABLE_NAME AS tabla_referenciada,
       kcu.REFERENCED_COLUMN_NAME AS columna_referenciada,
       rc.UPDATE_RULE AS regla_update, rc.DELETE_RULE AS regla_delete,
       cc.CHECK_CLAUSE AS expresion_check
FROM information_schema.TABLE_CONSTRAINTS tc
LEFT JOIN information_schema.KEY_COLUMN_USAGE kcu
  ON kcu.CONSTRAINT_SCHEMA=tc.CONSTRAINT_SCHEMA
 AND kcu.TABLE_NAME=tc.TABLE_NAME
 AND kcu.CONSTRAINT_NAME=tc.CONSTRAINT_NAME
LEFT JOIN information_schema.REFERENTIAL_CONSTRAINTS rc
  ON rc.CONSTRAINT_SCHEMA=tc.CONSTRAINT_SCHEMA
 AND rc.TABLE_NAME=tc.TABLE_NAME
 AND rc.CONSTRAINT_NAME=tc.CONSTRAINT_NAME
LEFT JOIN information_schema.CHECK_CONSTRAINTS cc
  ON cc.CONSTRAINT_SCHEMA=tc.CONSTRAINT_SCHEMA
 AND cc.CONSTRAINT_NAME=tc.CONSTRAINT_NAME
WHERE tc.TABLE_SCHEMA='conectasucre_final'
ORDER BY tc.TABLE_NAME,tc.CONSTRAINT_TYPE,tc.CONSTRAINT_NAME,kcu.ORDINAL_POSITION;

-- SEGUNDA CONSULTA (exportar como 13_03_DEFAULTS_MYSQL.csv):
SELECT TABLE_NAME AS tabla, COLUMN_NAME AS columna, COLUMN_DEFAULT AS valor_default,
       GENERATION_EXPRESSION AS expresion_generada, EXTRA AS propiedades
FROM information_schema.COLUMNS
WHERE TABLE_SCHEMA='conectasucre_final'
  AND (COLUMN_DEFAULT IS NOT NULL OR GENERATION_EXPRESSION <> '')
ORDER BY TABLE_NAME,ORDINAL_POSITION;
